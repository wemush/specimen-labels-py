"""Cross-library round-trip tests (WOLS 1.3.0 encrypted format).

Runs the shared matrix (``tests/interop/matrix.json``) through this library:

- labels generated here decrypt here (self round trip),
- the checked-in corpora generated by the published 1.3.0 releases of
  ``@wemush/wols`` and ``wols`` decrypt with this checkout,
- the verifier rejects corrupted labels, so a passing run means something.

The live cross-library runs (against ``@wemush/wols`` 1.3.0 from npm and its
``main`` branch) are in ``.github/workflows/interop.yml``. See
``tests/interop/README.md``.
"""

from __future__ import annotations

import copy
import importlib.util
import json
import sys
import unicodedata
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

pytest.importorskip("cryptography")

HERE = Path(__file__).parent
MATRIX_PATH = HERE / "matrix.json"
CORPORA = sorted((HERE / "corpus").glob("*.json"))


def _load_harness() -> ModuleType:
    spec = importlib.util.spec_from_file_location(
        "wols_interop_harness", HERE / "harness.py"
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


harness = _load_harness()
MATRIX: dict[str, Any] = harness.load_json(MATRIX_PATH)
CASE_IDS = [c["id"] for c in MATRIX["cases"]]


@pytest.fixture(scope="module")
def local_corpus() -> dict[str, Any]:
    return harness.generate(MATRIX, harness.matrix_sha256(MATRIX_PATH))


def _verify_one(corpus: dict[str, Any], case_id: str) -> Any:
    cases = [c for c in MATRIX["cases"] if c["id"] == case_id]
    (result,) = harness.verify({**MATRIX, "cases": cases}, corpus)
    return result


def test_matrix_is_ascii_with_unique_case_ids() -> None:
    MATRIX_PATH.read_bytes().decode("ascii")
    assert len(CASE_IDS) == len(set(CASE_IDS))
    known = set(CASE_IDS)
    for entry in MATRIX.get("expectedFailures", []):
        assert entry["case"] in known, entry
        assert entry.get("reason") and entry.get("reference"), entry


def test_matrix_covers_required_dimensions() -> None:
    cases = MATRIX["cases"]
    forms = {(c["form"], c["kdf"]) for c in cases}
    assert forms == {
        ("url", "pbkdf2"),
        ("url", "raw"),
        ("fields", "pbkdf2"),
        ("fields", "raw"),
    }
    iterations = {c.get("iterations") for c in cases if c["kdf"] == "pbkdf2"}
    assert {None, 100_000} <= iterations  # library default and the minimum
    assert any("sig" in c for c in cases)
    ids = "".join(c["specimenId"] for c in cases)
    for ch in "/?#&+% ":
        assert ch in ids
    assert any(ord(ch) > 0x7F for ch in ids)
    passphrases = [c["passphrase"] for c in cases if "passphrase" in c]
    assert any(p != unicodedata.normalize("NFC", p) for p in passphrases)


@pytest.mark.parametrize("case_id", CASE_IDS)
def test_python_self_roundtrip(local_corpus: dict[str, Any], case_id: str) -> None:
    result = _verify_one(local_corpus, case_id)
    assert result.status in ("pass", "xfail"), result.detail


@pytest.mark.parametrize("corpus_path", CORPORA, ids=[p.stem for p in CORPORA])
def test_checked_in_corpus_decrypts(corpus_path: Path) -> None:
    corpus = harness.load_json(corpus_path)
    assert corpus["matrixSha256"] == harness.matrix_sha256(MATRIX_PATH), (
        f"{corpus_path.name} was generated from a different matrix.json; "
        "regenerate it (see tests/interop/README.md)"
    )
    failures = [
        r for r in harness.verify(MATRIX, corpus) if r.status not in ("pass", "xfail")
    ]
    assert not failures, "\n".join(
        f"{r.status} {r.case_id}: {r.detail}" for r in failures
    )


def test_corpora_include_typescript_generator() -> None:
    languages = {harness.load_json(p)["generator"]["language"] for p in CORPORA}
    assert {"typescript", "python"} <= languages


def _mutated(corpus: dict[str, Any], case_id: str, fn: Any) -> dict[str, Any]:
    out = copy.deepcopy(corpus)
    out["cases"][case_id] = fn(out["cases"][case_id])
    return out


def _flip_ciphertext(entry: dict[str, Any]) -> dict[str, Any]:
    head, _, tail = entry["url"].partition("?e=")
    first = "B" if tail[0] == "A" else "A"
    return {"url": f"{head}?e={first}{tail[1:]}"}


@pytest.mark.parametrize(
    ("case_id", "mutate", "needle"),
    [
        ("url-raw-full", _flip_ciphertext, "AUTHENTICATION_FAILED"),
        (
            "url-pbkdf2-min-sig-base64url",
            lambda e: {"url": e["url"].split("&sig=")[0]},
            "sig",
        ),
        (
            "url-raw-id-spec-example",
            lambda e: {"url": e["url"].replace("Lab%20A", "Lab A")},
            "is not a valid RFC 3986 segment",
        ),
        (
            "url-raw-id-spec-example",
            lambda e: {"url": e["url"].replace("plate%2B3", "plate+3")},
            "MUST be encoded",
        ),
        (
            "url-pbkdf2-min-full",
            lambda e: {"url": e["url"].replace("&i=100000", "&i=200000")},
            "expected 100000",
        ),
        (
            "fields-raw-all",
            lambda e: {
                "document": {
                    **e["document"],
                    "batch": {
                        **e["document"]["batch"],
                        "iv": e["document"]["stage"]["iv"],
                    },
                }
            },
            "reused",
        ),
        (
            "fields-pbkdf2-min-all",
            lambda e: {
                "document": {
                    **e["document"],
                    "batch": e["document"]["creator"],
                    "creator": e["document"]["batch"],
                }
            },
            "AUTHENTICATION_FAILED",
        ),
    ],
)
def test_verifier_rejects_broken_labels(
    local_corpus: dict[str, Any], case_id: str, mutate: Any, needle: str
) -> None:
    result = _verify_one(_mutated(local_corpus, case_id, mutate), case_id)
    assert result.status == "fail"
    assert needle in result.detail


def test_cli_verify_exit_codes(tmp_path: Path, local_corpus: dict[str, Any]) -> None:
    good = tmp_path / "good.json"
    good.write_text(json.dumps(local_corpus), encoding="utf-8")
    assert harness.main(["harness.py", "verify", str(MATRIX_PATH), str(good)]) == 0
    bad = tmp_path / "bad.json"
    broken = _mutated(local_corpus, "url-raw-full", _flip_ciphertext)
    bad.write_text(json.dumps(broken), encoding="utf-8")
    assert harness.main(["harness.py", "verify", str(MATRIX_PATH), str(bad)]) == 1
